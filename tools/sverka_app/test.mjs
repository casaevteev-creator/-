/* Проверка сверки «Такском ↔ УМЦ» на двух реальных периодах.
 *
 *     npm install xlsx@0.18.5 playwright@1.49.1 --no-save
 *     python3 tools/sverka_app/build.py
 *     node tools/sverka_app/test.mjs
 *
 * Считает дважды: ядро сверки прямо в node — так видно цифры, — и то же
 * самое в браузере, чтобы приложение не разошлось с ядром.
 *
 * Август 11–31 — грязный период, на нём всё и найдено. Сентябрь 01–14 —
 * чистый: он сторожит ложные срабатывания, поэтому его числа в тесте
 * заданы жёстко. Если сверка начнёт находить в сентябре лишнее, тест упадёт.
 */
import pkg from "playwright";
import { createRequire } from "module";
import { fileURLToPath } from "url";
import { dirname, join, extname } from "path";
import { existsSync, readFileSync, copyFileSync, mkdtempSync, readdirSync } from "fs";
import { tmpdir } from "os";

const { chromium } = pkg;
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const require = createRequire(join(ROOT, "index.js"));
const XLSX = require("xlsx");

let провалов = 0;
function так(условие, что){
  if (!условие){ провалов++; console.error("  ✗ " + что); }
}
function равно(было, надо, что){
  так(было === надо, что + ": ожидалось " + надо + ", получено " + было);
}

/* ---------- ядро в node ---------- */

const ядро = () => {
  const src = ["utils.js", "umc_parsers.js", "sverka.js"]
    .map(f => readFileSync(join(ROOT, "tools", "lib", f), "utf8")).join("\n");
  return new Function("XLSX", src + "\nreturn {parseOfd, parsePayments, parseServices, сверка, КАССЫ};")(XLSX);
};
const LIB = ядро();

const второсорт = f => /^(1С-|Новая-|Старая-)/i.test(f) ? 1 : 0;
function файлы(период){
  const dir = join(ROOT, "data", "source", период);
  const все = readdirSync(dir).filter(f => /\.xlsx$/i.test(f))
    .sort((a, b) => второсорт(a) - второсорт(b) || a.localeCompare(b, "ru"));
  const занято = new Set();
  const взять = маска => {
    const f = все.find(x => !занято.has(x) && маска.test(x));
    if (f) занято.add(f);
    return f ? join(dir, f) : null;
  };
  return {ofd: взять(/такском|фискальн/i), pay: взять(/оплат/i), srv: взять(/услуг/i)};
}

function посчитать(период){
  const ф = файлы(период);
  const кн = п => XLSX.readFile(п, {cellDates:true});
  return LIB.сверка({
    ofd: LIB.parseOfd(кн(ф.ofd)),
    pay: ф.pay ? LIB.parsePayments(кн(ф.pay)) : null,
    services: ф.srv ? LIB.parseServices(кн(ф.srv)) : null
  });
}

const находка = (р, тип) => р.находки.find(н => н.тип === тип) || null;
const касса = (р, ключ) => р.кассы.find(к => к.ключ === ключ);

/* ---------- август: грязный период ---------- */

console.log("август 11–31.08.2026");
const авг = посчитать("2026-08");

равно(авг.период.join(" — "), "2026-08-11 — 2026-08-31", "период считается по самим выгрузкам");
равно(авг.итог.чеков, 810, "кассовых чеков в отчёте Такскома");
равно(авг.вердикт.наличные, 0, "наличные сходятся с фискальными данными до рубля");
равно(касса(авг, "к1").офд.нал, 24244900, "наличные корпуса 1 по фискальному накопителю");
равно(касса(авг, "к1").умц.нал, 24247900, "наличные корпуса 1 по УМЦ");
так(!авг.вердикт.чисто, "август не может быть чистым — на нём всё и найдено");

const вручную = находка(авг, "заведено-вручную");
так(!!вручную, "платежи, заведённые вручную, найдены");
равно(вручную.штук, 61, "сколько платежей заведено вручную");
равно(вручную.сумма, 522000, "на сколько заведено вручную");

const дубли = находка(авг, "задвоение");
так(!!дубли, "живое задвоение найдено");
равно(дубли.штук, 5, "групп живого задвоения");
равно(дубли.сумма, 64500, "денег в живом задвоении");

const возвр = находка(авг, "возврат-без-проводки");
так(!!возвр, "возвраты без проводки найдены");
так(возвр.строки.some(с => с.day === "2026-08-24" && с.сумма === 350000 && с.фд === "10892"),
    "24.08 возврат 350 000 по чеку ФД 10892 — тот самый случай из задания");

const терминал = находка(авг, "не-тот-терминал");
так(!!терминал, "перенос между терминалами найден");
равно(терминал.штук, 1, "переносов за август");
так(терминал.строки[0].day === "2026-08-13", "перенос приходится на 13.08");
равно(терминал.сумма, 1603500, "сумма переноса 13.08");
так(терминал.строки[0].откуда.indexOf("Облачная") === 0 &&
    терминал.строки[0].куда.indexOf("Корпус 1") === 0,
    "перенос идёт с облачной кассы на корпус 1");

так(авг.надёжно.нал && авг.надёжно.безнал,
    "в августе есть терминалы, значит обе стороны раскладываются по кассам");

/* ---------- сентябрь: чистый период, сторож ложных срабатываний ---------- */

console.log("сентябрь 01–14.09.2026");
const сен = посчитать("2026-09");

равно(сен.итог.чеков, 505, "кассовых чеков в отчёте Такскома");
равно(сен.вердикт.наличные, 0, "наличные сходятся до рубля");
равно(касса(сен, "к1").дельта.нал, 0, "наличные корпуса 1 сходятся со своей кассой");
равно(касса(сен, "к2").дельта.нал, 0, "наличные корпуса 2 сходятся со своей кассой");
равно(касса(сен, "к1").офд.безнал, 20512380, "эквайринг корпуса 1 по фискальному накопителю");

так(!сен.надёжно.безнал, "в сентябрьской выгрузке нет терминала — безнал по кассам не раскладывается");
так(сен.вердикт.пробелы.some(п => /терминал/i.test(п)),
    "про отсутствующий терминал сказано прямо, а не спрятано");
так(!находка(сен, "касса-мимо"),
    "без разбора безнала по кассам приложение не обвиняет кассу в пропаже");
так(!находка(сен, "не-тот-терминал"),
    "без терминалов перенос между ними не выдумывается");

равно(сен.вердикт.чинить, 3, "случаев, которые надо разобрать, в чистом периоде");
равно(находка(сен, "задвоение").сумма, 4500, "живое задвоение сентября");

const пара = находка(сен, "чек-и-возврат");
так(!!пара, "пара «пробили и тут же вернули» распознана");
равно(пара.штук, 1, "таких пар за сентябрь");
так(пара.вес === "знать", "такая пара не поломка: денег не двигалось");
так(!(находка(сен, "чек-без-операции") || {штук:0}).штук ||
    !находка(сен, "чек-без-операции").строки.some(с => с.day === "2026-09-09" && с.сумма === 10000),
    "аннулированный чек не показывается ещё и как пропавшая операция");

/* ---------- то же самое в браузере ---------- */

console.log("приложение");
const APP = join(ROOT, "out", process.env.APP || "sverka.html");
if (!existsSync(APP)){
  провалов++;
  console.error("  ✗ нет " + APP + " — соберите: python3 tools/sverka_app/build.py");
} else {
  const ф = файлы("2026-08");
  const TMP = mkdtempSync(join(tmpdir(), "sverka-test-"));
  const копии = [ф.ofd, ф.pay, ф.srv].filter(Boolean).map((п, i) => {
    const to = join(TMP, "f" + i + extname(п));
    copyFileSync(п, to);
    return to;
  });
  const BIN = ["/opt/pw-browsers/chromium-1194/chrome-linux/chrome",
               "/opt/pw-browsers/chromium/chrome-linux/chrome"].find(existsSync);
  const browser = await chromium.launch(BIN ? { executablePath: BIN } : {});
  const page = await browser.newPage({ acceptDownloads: true });
  const беды = [];
  page.on("pageerror", e => беды.push(e.message));
  await page.goto("file://" + APP);

  так(await page.locator("#run").isDisabled(), "без файлов сверять нечего — кнопка выключена");
  const ячейки = await page.locator(".slot input[type=file]").all();
  /* кладём файлы задом наперёд: приложение должно узнать их по содержимому */
  for (let i = 0; i < копии.length; i++)
    await ячейки[(i + 1) % ячейки.length].setInputFiles(копии[i]);
  так(!(await page.locator("#run").isDisabled()), "файлы приняты, кнопка включилась");
  await page.click("#run");
  await page.waitForSelector("#out section", { timeout: 60000 });

  равно((await page.locator("#err").innerText()).trim(), "", "приложение отработало без ошибок");
  так(!беды.length, "на странице нет исключений: " + беды.join("; "));

  /* в русской локали разряды разделяет неразрывный пробел — приводим к обычному */
  const текст = (await page.locator("#out").innerText()).replace(/\u00A0/g, " ");
  так(/Есть расхождения/.test(текст), "вердикт по августу — есть что чинить");
  так(/24 244 900/.test(текст), "наличные корпуса 1 показаны");
  так(/Возврат пробит кассой/.test(текст), "непроведённые возвраты попали на экран");
  так(/Эквайринговый терминал|эквайрингового терминала/.test(текст) === false,
      "при наличии терминалов приложение не просит их добавить");

  const скачивание = page.waitForEvent("download", { timeout: 30000 });
  await page.click("#save");
  const файл = await скачивание;
  /* имя файла headless-браузер не сообщает — он называет «download» любую
     ссылку со страницы file://, хоть blob, хоть data. Поэтому проверяем не
     имя, а содержимое: имя собирается из периода в имяФайла(). */
  const путь = await файл.path();
  const книга = XLSX.readFile(путь);
  const строки = XLSX.utils.sheet_to_json(книга.Sheets["Расхождения"], {header:1});
  так(строки.length > 50, "в файле весь список, а не первые строки экрана: " + строки.length);
  равно(строки[0][0], "Что", "первая колонка списка");
  так(строки.some(r => String(r[4] || "").indexOf("10892") >= 0),
      "конкретный чек из находки доехал до файла");
  await browser.close();
}

if (провалов){
  console.error("\nпровалов: " + провалов);
  process.exit(1);
}
console.log("\nвсё сошлось: август — 61 ручной платёж, задвоение 64 500, возврат 24.08 и перенос 13.08; " +
            "сентябрь — наличные в ноль, лишнего не найдено, аннулированный чек не считается пропажей; " +
            "приложение узнаёт файлы по содержимому и отдаёт список одним файлом");
