/* Сверка «Такском ↔ УМЦ»: чистый расчёт, без отрисовки.
 *
 * Эталон — фискальный накопитель: чек либо пробит, либо нет, касса не врёт.
 * Всё, что считается ниже, отвечает на один вопрос: где УМЦ расходится
 * с кассой и в какой документ идти смотреть.
 *
 * Работает поверх tools/lib/umc_parsers.js (parseOfd, parsePayments,
 * parseServices) и tools/lib/utils.js (S, num, R2).
 */

/* Три ККТ, два корпуса. Одна касса — облачная, на ней только карты,
   и эквайер у неё свой: расхождение по ней ищется не там, где по ВТБ. */
const КАССЫ = [
  {ключ:"к1",     офд:"Штрих",            имя:"Корпус 1 · Штрих-М",
   касса:"Корпус 1 / Штрих-М", терминал:"Корпус 1 / Терминал", пко:"К1",
   подразделение:"Форма строение 12", эквайер:"ВТБ"},
  {ключ:"к2",     офд:"0010439595007360", имя:"Корпус 2 · АТОЛ",
   касса:"Корпус 2 / АТОЛ", терминал:"Корпус 2 / Терминал ВТБ", пко:"К2",
   подразделение:"Форма строение 1", эквайер:"ВТБ"},
  {ключ:"облако", офд:"0007821495004509", имя:"Облачная касса · только карты",
   касса:"", терминал:"Онлайн-касса Карта", пко:"",
   подразделение:"", эквайер:"Альфа-Банк", толькоКарты:true}
];
const КАССА_НЕЯСНА = "неизвестная касса";

const кассаПоОФД = имя => {
  const k = КАССЫ.find(k => k.офд === имя);
  return k ? k.ключ : КАССА_НЕЯСНА;
};

/* К какой кассе относится строка реестра оплат. Три захода, в порядке
   надёжности: эквайринговый терминал, префикс в номере кассового ордера
   («ПКО №К1000000013»), касса документа оказания услуг. Если ни одного
   признака нет — честно говорим, что касса неизвестна, и не приписываем
   деньги наугад: приписанные наугад деньги сходятся только на бумаге. */
function кассаСтроки(строка, индекс){
  const поИмени = имя => {
    const по = КАССЫ.find(k => k.касса && k.касса === имя);
    return по ? по.ключ : "";
  };
  if (строка.терминал){
    const по = КАССЫ.find(k => k.терминал === строка.терминал);
    return по ? по.ключ : КАССА_НЕЯСНА;
  }
  if (/^К\d/.test(строка.num)){
    const по = КАССЫ.find(k => k.пко && строка.num.indexOf(k.пко) === 0);
    if (по) return по.ключ;
  }
  const прямо = поИмени((индекс.поДокументу || {})[строка.num]);
  if (прямо) return прямо;
  /* Документ, помеченный на удаление, в реестр услуг не попадает, а его
     минусовая оплата в реестре остаётся — и повисает без кассы. Берём кассу
     по другим услугам того же клиента в тот же день: сперва по совпадающей
     сумме, потом по дню целиком, и только если корпуса разные — сдаёмся. */
  const усл = (индекс.поКлиенту || {})[ключКлиента(строка.client, строка.day)] || [];
  const кассы = сп => [...new Set(сп.map(r => r.касса).filter(Boolean))];
  const поСумме = кассы(усл.filter(r => Math.abs(r.sum - Math.abs(строка.sum)) < 0.5));
  if (поСумме.length === 1) return поИмени(поСумме[0]) || КАССА_НЕЯСНА;
  const заДень = кассы(усл);
  if (заДень.length === 1) return поИмени(заДень[0]) || КАССА_НЕЯСНА;
  /* пациента могли обслужить в другой день, а оплату перевесить позже */
  const всеЕго = кассы((индекс.клиентЦеликом || {})[S(строка.client).toLowerCase()] || []);
  if (всеЕго.length === 1) return поИмени(всеЕго[0]) || КАССА_НЕЯСНА;
  return КАССА_НЕЯСНА;
}
const ключКлиента = (клиент, day) => S(клиент).toLowerCase() + "|" + day;

const пусто = () => ({нал:0, безнал:0, строк:0});
const кДню = (карта, day) => карта[day] ||
  (карта[day] = {day, офд:пусто(), умц:пусто()});

/* ---------- деньги по дням и кассам ---------- */

function деньги(ofd, pay, services, деньСтроки){
  const индекс = {поДокументу:{}, поКлиенту:{}, клиентЦеликом:{}};
  if (services) for (const r of services.recs){
    индекс.поДокументу[r.num] = r.касса;
    const k = ключКлиента(r.client, r.day), кл = S(r.client).toLowerCase();
    (индекс.поКлиенту[k] || (индекс.поКлиенту[k] = [])).push(r);
    (индекс.клиентЦеликом[кл] || (индекс.клиентЦеликом[кл] = [])).push(r);
  }

  const дни = {};                       /* day -> {офд, умц} по всем кассам */
  const кассы = {};                     /* ключ кассы -> {итог, дни} */
  const К = ключ => кассы[ключ] || (кассы[ключ] = {ключ, дни:{}, офд:пусто(), умц:пусто()});

  for (const ч of ofd.чеки){
    if (!ч.day) continue;
    const к = К(кассаПоОФД(ч.касса));
    const д = кДню(к.дни, ч.day), общ = кДню(дни, ч.day);
    for (const где of [д.офд, общ.офд, к.офд]){
      где.нал = R2(где.нал + ч.нал); где.безнал = R2(где.безнал + ч.безнал); где.строк++;
    }
  }
  const строкиКассы = {};
  if (pay) for (const с of pay.строки){
    /* Возврат, оформленный в УМЦ соседним днём, кладём в день чека: дата
       фискального документа — это факт, дата оформления — как получилось.
       Иначе один сдвинутый возврат ломает сразу два дня. */
    const day = (деньСтроки && деньСтроки.get(с)) || с.day;
    if (!day) continue;
    const ключ = кассаСтроки(с, индекс);
    (строкиКассы[ключ] || (строкиКассы[ключ] = [])).push(с);
    const к = К(ключ), д = кДню(к.дни, day), общ = кДню(дни, day);
    const поле = с.kind === "Наличными" ? "нал" : "безнал";
    for (const где of [д.умц, общ.умц, к.умц]){ где[поле] = R2(где[поле] + с.sum); где.строк++; }
  }
  return {дни, кассы, строкиКассы, индекс};
}

const дельта = (а, б) => ({нал: R2(а.нал - б.нал), безнал: R2(а.безнал - б.безнал)});
const мелочь = x => Math.abs(x) < 0.5;

/* ---------- 1 и 9. День не сошёлся: касса видит не то, что УМЦ ---------- */

/* Сначала общий итог дня, потом — разрез по кассам. Разрез отдельно, потому
   что общая сумма может сойтись, а по кассам разъехаться: тогда деньги
   записаны не на тот аппарат, и обе кассовые книги врут. */
function дниРасхождений(д, объяснено){
  const out = [];
  for (const day of Object.keys(д.дни).sort()){
    const {офд, умц} = д.дни[day];
    const раз = дельта(офд, умц);
    /* Возврат, который касса пробила, а УМЦ не провела, виден в дне дважды:
       сам по себе и как «в УМЦ денег больше». Вычитаем уже названное,
       чтобы одна ошибка не считалась двумя. */
    const уже = объяснено[day];
    if (уже){ раз.нал = R2(раз.нал - уже.нал); раз.безнал = R2(раз.безнал - уже.безнал); }
    if (мелочь(раз.нал) && мелочь(раз.безнал)) continue;
    out.push({day, офд, умц, ...раз, объяснено: уже || null});
  }
  return out;
}

/* Чем уже объяснена разница дня: возврат без проводки занижает сторону ОФД,
   возврат без чека — сторону УМЦ. */
function объясненияДней(возвр){
  const карта = {};
  const в = (day, поле, сколько) => {
    const о = карта[day] || (карта[day] = {нал:0, безнал:0});
    о[поле] = R2(о[поле] + сколько);
  };
  for (const ч of возвр.нет)
    в(ч.day, Math.abs(ч.нал) > 0.5 ? "нал" : "безнал", -Math.abs(ч.сумма));
  for (const с of возвр.безЧека)
    в(с.day, с.kind === "Наличными" ? "нал" : "безнал", Math.abs(с.сумма));
  return карта;
}

/* Разложение по кассам честно ровно настолько, насколько все деньги
   удалось отнести к аппарату. Если хоть часть безнала повисла без кассы —
   безналичные выводы по кассам не делаем вовсе: сравнивать полный ОФД
   с половиной УМЦ значит выдумывать расхождение на ровном месте. */
function кассыПоДням(д, надёжно){
  const out = [];
  for (const ключ of Object.keys(д.кассы)){
    if (ключ === КАССА_НЕЯСНА) continue;
    const к = д.кассы[ключ];
    for (const day of Object.keys(к.дни).sort()){
      const {офд, умц} = к.дни[day];
      const раз = дельта(офд, умц);
      if (!надёжно.нал) раз.нал = 0;
      if (!надёжно.безнал) раз.безнал = 0;
      if (мелочь(раз.нал) && мелочь(раз.безнал)) continue;
      out.push({ключ, day, офд, умц, ...раз});
    }
  }
  out.sort((a, b) => a.day < b.day ? -1 : a.day > b.day ? 1 : 0);
  return out;
}

/* ---------- 3. Оплата заведена не на тот терминал ----------

   Признак железный: за один день у одной кассы ровно столько же лишних
   денег, сколько у другой не хватает. Фискальный накопитель знает, какой
   аппарат пробил чек, поэтому прав он, а не УМЦ. */
function неТотТерминал(поКассам){
  const поДням = {};
  for (const р of поКассам) (поДням[р.day] || (поДням[р.day] = [])).push(р);
  const out = [];
  for (const day of Object.keys(поДням).sort()){
    const лишние = поДням[day].filter(x => x.безнал < -0.5);   /* у УМЦ больше */
    const нехватка = поДням[day].filter(x => x.безнал > 0.5);  /* у УМЦ меньше */
    for (const л of лишние) for (const н of нехватка){
      if (Math.abs(Math.abs(л.безнал) - н.безнал) > 0.5) continue;
      out.push({day, сумма: R2(н.безнал), откуда: л.ключ, куда: н.ключ});
    }
  }
  return out;
}

/* ---------- 2 и 8. Как заведена строка оплаты ----------

   Платёж, заведённый руками, приходит с временем 00:00:00 и без привязки
   к чеку. Деньги при этом настоящие — чек в ОФД есть, — но проверить их
   нечем, и в обмен они не попадают. Это не разовая ошибка, а дыра в
   порядке работы: лечится тем, чтобы не заводить платежи руками. */
function какЗаведены(pay){
  const карты = (pay && pay.карты) || [];
  const вручную = карты.filter(к => к.вручную);
  const естьПоле = карты.some(к => к.терминал);
  const безТерминала = естьПоле ? карты.filter(к => !к.терминал) : [];
  const сумма = сп => R2(сп.reduce((s, x) => s + x.sum, 0));
  return {вручную, безТерминала, естьПоле,
          вручнуюНа: сумма(вручную), безТерминалаНа: сумма(безТерминала)};
}

/* ---------- 4. Возврат пробит кассой, но не проведён в УМЦ ----------

   Сопоставляем по сумме. День возврата в УМЦ и день чека расходятся чаще,
   чем кажется: администратор оформляет возврат утром, а чек пробивают
   вечером или наоборот. Поэтому сначала ищем пару в тот же день, потом —
   в соседний, и это две разные новости: «нет вовсе» и «стоит не тем днём». */
function возвраты(ofd, pay){
  const чеки = ofd.чеки.filter(ч => ч.возврат && ч.day);
  const свободные = ((pay && pay.строки) || [])
        .filter(с => с.sum < -0.5 || /Возврат/.test(с.док))
        .map(с => ({...с, исход:с, сумма: R2(Math.abs(с.sum)), занят:false}));
  const найти = (сумма, дни) => свободные.find(
    с => !с.занят && Math.abs(с.сумма - сумма) < 0.5 && дни.indexOf(с.day) >= 0);
  const сдвиг = (day, шаг) => {
    const d = new Date(day + "T00:00:00Z");
    d.setUTCDate(d.getUTCDate() + шаг);
    return d.toISOString().slice(0, 10);
  };
  const нет = [], сдвинуты = [];
  for (const ч of чеки){
    const сумма = R2(Math.abs(ч.сумма));
    const вДень = найти(сумма, [ч.day]);
    if (вДень){ вДень.занят = true; continue; }
    const рядом = найти(сумма, [сдвиг(ч.day, -1), сдвиг(ч.day, 1)]);
    if (рядом){ рядом.занят = true; сдвинуты.push({чек:ч, строка:рядом}); continue; }
    нет.push(ч);
  }
  /* обратная сторона: возврат оформлен в УМЦ, а чека на него нет */
  const безЧека = свободные.filter(с => !с.занят);
  return {нет, сдвинуты, безЧека,
          нетНа: R2(нет.reduce((s, ч) => s + Math.abs(ч.сумма), 0)),
          безЧекаНа: R2(безЧека.reduce((s, с) => s + с.сумма, 0))};
}

/* ---------- 5. Касса вообще не попадает в УМЦ ---------- */

function кассаМимо(д, надёжно){
  const out = [];
  for (const к of КАССЫ){
    const с = д.кассы[к.ключ];
    if (!с) continue;
    /* касса, где деньги идут только картой, без разбора безнала не судится */
    if (!надёжно.безнал && (к.толькоКарты || с.офд.безнал > с.офд.нал)) continue;
    const деньгиОФД = R2(с.офд.нал + (надёжно.безнал ? с.офд.безнал : 0));
    const деньгиУМЦ = R2(с.умц.нал + (надёжно.безнал ? с.умц.безнал : 0));
    if (деньгиОФД < 1) continue;
    const доля = деньгиУМЦ / деньгиОФД;
    if (доля < 0.5) out.push({ключ:к.ключ, офд:деньгиОФД, умц:деньгиУМЦ,
                              недобор:R2(деньгиОФД - деньгиУМЦ), доля});
  }
  return out;
}

/* ---------- 6. Услуга заведена, а чек не пробит ----------

   «Нет чека» значит три разные вещи, и путать их нельзя: услугу не
   оплатили вовсе (выручки нет), оплатили авансом и не пробили чек зачёта
   (выручка есть, нарушение по кассе), оплатили зачётом против гонорара
   врача (выручка есть, чек не нужен). Программа различает первое от
   остальных по одному признаку: видно ли деньги по этому документу
   в реестре оплат. */
function услугиБезЧека(services, pay){
  if (!services) return null;
  const оплачено = {};
  if (pay) for (const с of pay.строки) оплачено[с.num] = R2((оплачено[с.num] || 0) + с.sum);
  const без = services.recs.filter(r => !r.чек && r.sum > 0);
  const деньгиЕсть = [], денегНет = [];
  for (const r of без) (оплачено[r.num] > 0.5 ? деньгиЕсть : денегНет).push(
    {...r, оплачено: R2(оплачено[r.num] || 0)});
  const сумма = сп => R2(сп.reduce((s, x) => s + x.sum, 0));
  деньгиЕсть.sort((a, b) => b.sum - a.sum);
  денегНет.sort((a, b) => b.sum - a.sum);
  return {деньгиЕсть, денегНет, деньгиЕстьНа: сумма(деньгиЕсть), денегНетНа: сумма(денегНет)};
}

/* ---------- 1. Чек есть, а в УМЦ его не видно ----------

   День, который не сошёлся, — это ещё не адрес. Адрес — конкретный чек.
   Раскладываем безналичные чеки дня против строк оплат того же дня по
   суммам: что осталось без пары, то и не заведено. Совпадение по сумме
   не доказательство, но в дне, где денег и правда не хватает ровно на эту
   сумму, другого объяснения обычно нет. */
function чекиБезПары(ofd, pay, расхождения){
  const плохиеДни = new Set(расхождения.filter(р => р.безнал > 0.5).map(р => р.day));
  if (!плохиеДни.size) return [];
  const свободные = ((pay && pay.строки) || [])
        .filter(с => с.kind === "Безналичными" && с.sum > 0.5)
        .map(с => ({...с, занят:false}));
  const out = [];
  for (const day of [...плохиеДни].sort()){
    const чеки = ofd.чеки.filter(ч => ч.day === day && !ч.возврат && ч.безнал > 0.5);
    const строки = свободные.filter(с => с.day === day);
    for (const ч of чеки){
      const пара = строки.find(с => !с.занят && Math.abs(с.sum - ч.безнал) < 0.5);
      if (пара) пара.занят = true; else out.push(ч);
    }
  }
  return out;
}

/* ---------- 7. Задвоенные услуги ----------
   Считаем по деньгам, а не по числу документов: администратор перевешивает
   оплату на правильный документ и помечает лишний на удаление, и тогда в
   реестре услуг обе половинки стоят плюсом, а в реестре оплат у близнеца
   минус. Такая пара погашена, денег пришло один раз. */
function задвоение(services, pay){
  if (!services) return null;
  /* Ищем среди документов с пробитым чеком: там, где чека нет, нет и денег,
     а значит нет и задвоения — только незакрытые документы. */
  return разборДублей(duplicates(services.recs.filter(r => r.чек)), pay);
}

/* ---------- сборка ---------- */

function сверка({ofd, pay, services}){
  if (!ofd) return null;
  const возвр = возвраты(ofd, pay);
  const деньСтроки = new Map();
  for (const п of возвр.сдвинуты) деньСтроки.set(п.строка.исход, п.чек.day);
  const д = деньги(ofd, pay, services, деньСтроки);
  /* деньги, которые не удалось отнести ни к одной кассе, обесценивают весь
     разрез по кассам — по такому каналу выводов не делаем */
  const неизв = д.кассы[КАССА_НЕЯСНА];
  const итогУМЦ = суммарно(д.дни, "умц");
  /* полпроцента оборота — предел, после которого разрез по кассам врёт
     больше, чем показывает */
  const тянет = (повисло, всего) => !повисло || Math.abs(повисло) <= Math.abs(всего) * 0.005;
  const надёжно = {нал: !неизв || тянет(неизв.умц.нал, итогУМЦ.нал),
                   безнал: !неизв || тянет(неизв.умц.безнал, итогУМЦ.безнал)};
  const поДням = дниРасхождений(д, объясненияДней(возвр));
  const поКассам = кассыПоДням(д, надёжно);
  const терминалы = надёжно.безнал ? неТотТерминал(поКассам) : [];
  /* день, который объяснён переносом между терминалами, из «чек есть,
     а в УМЦ его нет» вычитаем: деньги на месте, ошибка в аналитике */
  const перенесённые = new Set(терминалы.map(т => т.day));
  const общиеРасхождения = поДням.filter(р => !(мелочь(р.нал) && перенесённые.has(р.day)));
  const результат = {
    период: периодДанных(ofd, pay, services),
    итог: {
      офд: суммарно(д.дни, "офд"), умц: суммарно(д.дни, "умц"),
      чеков: ofd.чеки.length
    },
    кассы: КАССЫ.map(к => ({...к, ...(д.кассы[к.ключ] || {офд:пусто(), умц:пусто(), дни:{}}),
                            дельта: дельта((д.кассы[к.ключ] || {офд:пусто()}).офд,
                                           (д.кассы[к.ключ] || {умц:пусто()}).умц)})),
    неизвестнаяКасса: д.кассы[КАССА_НЕЯСНА] || null,
    дни: поДням, поКассам, терминалы,
    чекиБезПары: чекиБезПары(ofd, pay, общиеРасхождения),
    какЗаведены: какЗаведены(pay),
    возвраты: возвр,
    кассаМимо: кассаМимо(д, надёжно), надёжно,
    услугиБезЧека: услугиБезЧека(services, pay),
    задвоение: задвоение(services, pay),
    нет: {оплат: !pay, услуг: !services}
  };
  /* Ошибочный чек, который тут же аннулировали возвратом, выглядит как две
     поломки сразу: приход без пары и возврат без проводки. На деле денег не
     двигалось и заводить в УМЦ нечего — сводим такие пары вместе. */
  результат.самоотмена = свестиСамоотмену(результат);
  результат.находки = находки(результат);
  результат.вердикт = вердикт(результат);
  return результат;
}

function свестиСамоотмену(р){
  const пары = [];
  const ключ = ч => ч.day + "|" + ч.касса + "|" + R2(Math.abs(ч.безнал || ч.нал || ч.сумма));
  const возвраты = new Map();
  for (const ч of р.возвраты.нет) возвраты.set(ключ(ч), ч);
  р.чекиБезПары = р.чекиБезПары.filter(ч => {
    const пара = возвраты.get(ключ(ч));
    if (!пара) return true;
    возвраты.delete(ключ(ч));
    пары.push({приход:ч, возврат:пара});
    return false;
  });
  р.возвраты.нет = р.возвраты.нет.filter(ч => пары.every(п => п.возврат !== ч));
  р.возвраты.нетНа = R2(р.возвраты.нет.reduce((s, ч) => s + Math.abs(ч.сумма), 0));
  return пары;
}

function суммарно(дни, чей){
  const и = пусто();
  for (const day in дни){
    и.нал = R2(и.нал + дни[day][чей].нал);
    и.безнал = R2(и.безнал + дни[day][чей].безнал);
    и.строк += дни[day][чей].строк;
  }
  return и;
}

function периодДанных(ofd, pay, services){
  const дни = [];
  for (const ч of ofd.чеки) if (ч.day) дни.push(ч.day);
  if (pay) for (const с of pay.строки) if (с.day) дни.push(с.day);
  if (services) for (const r of services.recs) if (r.day) дни.push(r.day);
  дни.sort();
  return дни.length ? [дни[0], дни[дни.length - 1]] : ["", ""];
}

/* Находка — это не «расхождение на столько-то рублей», а «иди и посмотри
   вот это». Поэтому у каждой есть вес: чинить сейчас, проверить глазами
   или просто знать. Порядок — по весу, внутри веса по деньгам. */
