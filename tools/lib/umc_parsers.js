/* Разборщики выгрузок УМЦ и отчёта ОФД — общий код двух приложений.
 *
 *   tools/obmen_app/   обмен УМЦ -> 1С:Бухгалтерия
 *   tools/sverka_app/  сверка «Такском ↔ УМЦ»
 *
 * Модуль вшивается в оба приложения при сборке (build.py), поэтому он не
 * объявляет ни S, ни num, ни R2, ни XLSX — они уже есть в приложении.
 * Ничего, кроме разбора таблиц, тут быть не должно: правки файла обмена и
 * отрисовка живут каждая в своём приложении.
 */
/* ---------- чтение xlsx ---------- */
function realRange(ws){
  const r0 = XLSX.utils.decode_range(ws["!ref"] || "A1");
  let sr = r0.s.r, sc = r0.s.c, er = r0.e.r, ec = r0.e.c;
  for (const k in ws){
    if (k.charCodeAt(0) === 33) continue;
    const a = XLSX.utils.decode_cell(k);
    if (a.r < sr) sr = a.r; if (a.c < sc) sc = a.c;
    if (a.r > er) er = a.r; if (a.c > ec) ec = a.c;
  }
  return {s:{r:sr, c:sc}, e:{r:er, c:ec}};
}
function gridOf(ws){                    /* объявленный диапазон листа у 1С врёт */
  const rng = realRange(ws), rows = [];
  for (let r = rng.s.r; r <= rng.e.r; r++){
    const row = [];
    for (let c = rng.s.c; c <= rng.e.c; c++){
      const cell = ws[XLSX.utils.encode_cell({r, c})];
      row.push(cell ? cell.v : null);
    }
    rows.push(row);
  }
  return rows;
}
function findHead(rows, must){
  for (let r = 0; r < Math.min(rows.length, 30); r++){
    const h = rows[r].map(S);
    if (must.every(n => h.indexOf(n) >= 0)) return {r, h};
  }
  return null;
}
const часыOf = v => v instanceof Date && !isNaN(v)
  ? String(v.getUTCHours()).padStart(2, "0") + ":" + String(v.getUTCMinutes()).padStart(2, "0")
  : (S(v).match(/\d{1,2}:\d{2}/) || [""])[0];
const dayOf = v => {
  /* SheetJS отдаёт даты объектами. Такском помечает время буквой Z, хотя
     показывает московское («14/09/26 22:59»), поэтому день берём по UTC:
     местными часами вечерний чек уехал бы на сутки вперёд у всех, кто не
     живёт по Гринвичу. */
  if (v instanceof Date && !isNaN(v))
    return v.getUTCFullYear() + "-" + String(v.getUTCMonth() + 1).padStart(2, "0") +
           "-" + String(v.getUTCDate()).padStart(2, "0");
  const s = S(v);
  let m = /(\d{4})-(\d{2})-(\d{2})/.exec(s);
  if (m) return m[1] + "-" + m[2] + "-" + m[3];
  m = /(\d{2})\.(\d{2})\.(\d{4})/.exec(s);
  return m ? m[3] + "-" + m[2] + "-" + m[1] : "";
};

/* отчёт ОФД: живые деньги и зачёт аванса по дням */
function parseOfd(wb){
  for (const name of wb.SheetNames){
    const rows = gridOf(wb.Sheets[name]);
    const H = findHead(rows, ["Наличными", "Сумма"]);
    if (!H) continue;
    const ci = {};
    ["Дата и время","Документ","Тип операции","Наличными","Безналичными","Аванс","Сумма",
     "Название ККТ","Зав. № ККТ","Торговая точка","№ ФД","Кассир","№ смены",
     "Предоплата 100%","Частичная предоплата","Аванс расчет","Полный расчет"]
      .forEach(k => ci[k] = H.h.indexOf(k));
    if (ci["Документ"] < 0) continue;
    /* Итоги по кассам отвечают на вопрос «сошлось или нет», а чинить УМЦ
       заказчик идёт по конкретному чеку: дата, время, сумма, номер ФД,
       кассир. Поэтому рядом с итогами держим и сами чеки. */
    const t = {checks:0, days:{}, cash:0, card:0, adv:0, refund:0, kkt:{}, чеки:[]};
    for (let r = H.r + 1; r < rows.length; r++){
      if (S(rows[r][ci["Документ"]]) !== "Кассовый чек") continue;
      const sum = num(rows[r][ci["Сумма"]]);
      if (!sum) continue;
      t.checks++;
      const cash = num(rows[r][ci["Наличными"]]), card = num(rows[r][ci["Безналичными"]]),
            adv = ci["Аванс"] >= 0 ? num(rows[r][ci["Аванс"]]) : 0;
      t.cash += cash; t.card += card; t.adv += adv;
      if (/озврат/i.test(S(rows[r][ci["Тип операции"]]))) t.refund += Math.abs(sum);
      const day = dayOf(rows[r][ci["Дата и время"]]);
      /* касса подписана то названием, то заводским номером — берём, что есть */
      const имя = S(rows[r][ci["Название ККТ"]]) || S(rows[r][ci["Зав. № ККТ"]]) || "без названия";
      const k = t.kkt[имя] || (t.kkt[имя] = {cash:0, card:0, adv:0, checks:0, days:{},
                                             авансовые:0, полные:0, нал:{},
                                             точка:S(rows[r][ci["Торговая точка"]])});
      k.cash += cash; k.card += card; k.adv += adv; k.checks++;
      if (day) k.нал[day] = R2((k.нал[day] || 0) + cash);
      /* чек возврата — доказательство, что деньги вернули; если в выгрузке
         такого возврата нет, её выручка завышена ровно на эту сумму */
      if (/озврат/i.test(S(rows[r][ci["Тип операции"]])) && card < -0.5)
        (k.возвраты || (k.возвраты = [])).push({day, сумма:R2(-card)});
      /* признак расчёта (реквизит 1214) решает проводку: аванс — это Кт 62.Р,
         полный расчёт — Кт 90.01. Для кассы, где всё авансы, выручки нет вовсе. */
      ["Предоплата 100%", "Частичная предоплата", "Аванс расчет"].forEach(п => {
        if (ci[п] >= 0) k.авансовые += num(rows[r][ci[п]]);
      });
      if (ci["Полный расчет"] >= 0) k.полные += num(rows[r][ci["Полный расчет"]]);
      const признак = ["Предоплата 100%", "Частичная предоплата", "Аванс расчет"]
            .some(п => ci[п] >= 0 && num(rows[r][ci[п]])) ? "аванс"
          : (ci["Полный расчет"] >= 0 && num(rows[r][ci["Полный расчет"]])) ? "полный расчёт" : "";
      t.чеки.push({
        day, время: часыOf(rows[r][ci["Дата и время"]]),
        касса: имя, точка: S(rows[r][ci["Торговая точка"]]),
        возврат: /озврат/i.test(S(rows[r][ci["Тип операции"]])),
        нал: R2(cash), безнал: R2(card), зачётАванса: R2(adv), сумма: R2(sum), признак,
        фд: S(rows[r][ci["№ ФД"]]), смена: S(rows[r][ci["№ смены"]]),
        кассир: S(rows[r][ci["Кассир"]])
      });
      if (day) k.days[day] = (k.days[day] || 0) + card;
      if (!day) continue;
      const d = t.days[day] || (t.days[day] = {cash:0, card:0, adv:0});
      d.cash += cash; d.card += card; d.adv += adv;
    }
    return t;
  }
  return null;
}

/* Отчёт ОФД обычно выгружают за месяц, а файл обмена может быть за один день —
   так и работают, когда проверяют день за днём. Сравнивать месяц кассы с сутками
   выгрузки бессмысленно, поэтому обрезаем фискальные данные по периоду файла. */
function обрезатьОФД(ofd, период){
  const [от, до] = период;
  if (!от || !до) return ofd;
  const вПериоде = d => d >= от && d <= до;
  const свой = {checks:0, days:{}, cash:0, card:0, adv:0, refund:ofd.refund, kkt:{},
                обрезан:false, период};
  for (const d in ofd.days){
    if (!вПериоде(d)) { свой.обрезан = true; continue; }
    свой.days[d] = ofd.days[d];
    свой.cash += ofd.days[d].cash; свой.card += ofd.days[d].card; свой.adv += ofd.days[d].adv;
  }
  for (const имя in ofd.kkt){
    const k = ofd.kkt[имя], н = {cash:0, card:0, adv:0, checks:0, days:{}, нал:{},
                                 авансовые:0, полные:0, точка:k.точка, возвраты:[]};
    for (const d in k.days) if (вПериоде(d)){ н.days[d] = k.days[d]; н.card += k.days[d]; }
    for (const d in (k.нал || {})) if (вПериоде(d)){ н.нал[d] = k.нал[d]; н.cash += k.нал[d]; }
    (k.возвраты || []).forEach(в => { if (вПериоде(в.day)) н.возвраты.push(в); });
    /* признак расчёта и чеки по кассе за период точно не пересчитать: в разрезе
       по дням их нет. Берём долю — она нужна только чтобы понять, авансовая
       касса или выручковая, а это свойство кассы, а не периода. */
    const доля = k.card ? н.card / k.card : 0;
    н.авансовые = k.авансовые * доля; н.полные = k.полные * доля;
    н.checks = Math.round(k.checks * доля);
    свой.kkt[имя] = н;
  }
  свой.checks = Object.values(свой.kkt).reduce((s, k) => s + k.checks, 0) || ofd.checks;
  return свой;
}

/* Реестр услуг и реестр оплат выгружают за месяц, а файл обмена может быть
   за один день. Сравнивать их напрямую нельзя: реестр покажет месяц работы
   против суток выгрузки, и получится «выгрузка меньше реестра на миллионы».
   Обрезаем так же, как фискальные данные, — по периоду файла обмена. */
function обрезатьРеестр(recs, период){
  const [от, до] = период;
  if (!от || !до) return {recs, убрано:0};
  const свои = recs.filter(r => !r.day || (r.day >= от && r.day <= до));
  return {recs:свои, убрано:recs.length - свои.length};
}

/* реестр оплат: ищем задвоенные услуги */
const клиент = (row, label) => {
  for (let c = 1; c < row.length; c++){
    const v = S(row[c]);
    if (v && typeof row[c] === "string" && v !== label) return v;
  }
  return "";
};
function parsePayments(wb){
  for (const name of wb.SheetNames){
    const rows = gridOf(wb.Sheets[name]);
    let kind = "", recs = [], total = 0;
    /* Платёж, заведённый администратором руками, приходит с временем 00:00:00 —
       у него нет привязки к чеку, и фильтр «Только фискализированные документы»
       выкидывает его из выгрузки. Деньги при этом настоящие: чек по ним в ОФД
       есть. Отсюда систематический недобор облачной кассы. */
    const карты = [];
    /* Обмену хватало услуг и карт, сверке — нет: возврат по карте, приходный
       и расходный ордера тоже двигают деньги, и без них день не сойдётся
       с фискальным накопителем. Поэтому рядом лежат все строки подряд,
       каждая со своим типом документа. */
    const строки = [];
    const итоги = {"Наличными":0, "Безналичными":0, "Итого":0};
    const числоСправа = row => {
      for (let c = row.length - 1; c >= 1; c--) if (typeof row[c] === "number") return row[c];
      return 0;
    };
    for (const row of rows){
      const label = S(row[0]);
      /* в этих строках лежит итог раздела — сколько всего денег видит УМЦ */
      if (label === "Наличными" || label === "Безналичными"){
        kind = label; итоги[label] = числоСправа(row); continue; }
      if (label === "Итого") { итоги["Итого"] = числоСправа(row); kind = ""; continue; }
      /* если в отчёт добавлен эквайринговый терминал, он приклеен к названию
         документа после запятой — «… от 13.08.2026 9:22:45, Онлайн-касса Карта» */
      const к = /^Оплата платежной картой\s+(\S+)\s+от\s+(\d{2}\.\d{2}\.\d{4})\s+(\d{1,2}:\d{2}:\d{2})\s*(?:,\s*(.*))?$/.exec(label);
      if (к){
        const s = числоСправа(row);
        if (s){
          const оплата = {num:к[1], day:dayOf(к[2]), time:к[3], sum:s,
                          терминал:S(к[4]), вручную:к[3] === "0:00:00"};
          карты.push(оплата);
          строки.push({...оплата, kind, док:"Оплата платежной картой", client:клиент(row, label)});
        }
        continue;
      }
      /* прочие документы реестра: возврат по карте, приходный и расходный
         ордера. Номер кассового ордера подписан кассой — «К1000000013». */
      const п = /^(Возврат по платежной карте|Приходный кассовый ордер|Расходный кассовый ордер)\s+(\S+)\s+от\s+(\d{2}\.\d{2}\.\d{4})\s+(\d{1,2}:\d{2}:\d{2})\s*(?:,\s*(.*))?$/.exec(label);
      if (п){
        const s = числоСправа(row);
        if (s) строки.push({kind, док:п[1], num:п[2], day:dayOf(п[3]), time:п[4],
                            sum:п[1] === "Расходный кассовый ордер" ? -Math.abs(s) : s,
                            терминал:S(п[5]), вручную:п[4] === "0:00:00",
                            client:клиент(row, label)});
        continue;
      }
      if (!label || label.indexOf("Оказание услуг") !== 0) continue;
      let sum = 0;
      for (let c = row.length - 1; c >= 1; c--) if (typeof row[c] === "number"){ sum = row[c]; break; }
      if (!sum) continue;
      const m = /Оказание услуг\s+(\S+)\s+от\s+(\d{2}\.\d{2}\.\d{4})\s+(\d{1,2}:\d{2}:\d{2})/.exec(label);
      if (!m) continue;
      const client = клиент(row, label);
      recs.push({kind, num:m[1], day:dayOf(m[2]), time:m[3], client, sum});
      строки.push({kind, док:"Оказание услуг", num:m[1], day:dayOf(m[2]), time:m[3],
                   sum, терминал:"", вручную:m[3] === "0:00:00", client});
      total += sum;
    }
    if (recs.length || карты.length) return {recs, total, итоги, карты, строки};
  }
  return null;
}
function duplicates(recs){
  const g = {};
  for (const r of recs){
    const k = r.day + "|" + r.client + "|" + (r.врач || "") + "|" + r.sum;
    (g[k] || (g[k] = [])).push(r);
  }
  const out = [];
  for (const k in g) if (g[k].length > 1) out.push(g[k]);
  out.sort((a, b) => a[0].day < b[0].day ? -1 : 1);
  return out;
}

/* Задвоение задвоению рознь, и это главное, что нельзя путать.
   Администратор, заметив лишний документ, перевешивает оплату на правильный
   и помечает лишний на удаление. В реестре услуг обе половинки такой пары
   так и стоят плюсом — колонка «Сумма» знака не имеет, — и со стороны кажется,
   будто деньги посчитаны дважды. В реестре оплат видно правду: у одного
   документа плюс, у его близнеца ровно такой же минус, денег пришло один раз.
   Поэтому вывод делаем по деньгам, а не по количеству документов:
   сколько нетто оплачено по документам группы — одна сумма или две. */
function нетоПоДокументам(pay){
  const н = {};
  if (pay) for (const r of pay.recs) н[r.num] = R2((н[r.num] || 0) + r.sum);
  return н;
}
function разборДублей(группы, pay){
  const нетто = нетоПоДокументам(pay);
  const из = группы.map(g => {
    const номера = g.map(x => x.num);
    const известно = pay && номера.some(n => нетто[n] !== undefined);
    const оплачено = R2(номера.reduce((s, n) => s + (нетто[n] || 0), 0));
    const одна = g[0].sum;
    /* «погашен» — денег по группе не больше, чем за одну услугу */
    const статус = !известно ? "неясно" : оплачено <= одна * 1.005 + 1 ? "погашен" : "живой";
    return {g, номера, оплачено, одна, лишних: g.length - 1,
            лишниеДеньги: статус === "живой" ? R2(оплачено - одна) : 0, статус};
  });
  const по = s => из.filter(x => x.статус === s);
  return {
    все: из, живые: по("живой"), погашенные: по("погашен"), неясные: по("неясно"),
    ущерб: по("живой").reduce((s, x) => s + x.лишниеДеньги, 0),
    погашеноНа: по("погашен").reduce((s, x) => s + x.одна * x.лишних, 0)
  };
}

/* Реестр услуг: тут видно то, чего не видно нигде больше — какие услуги
   заведены без пробитого чека. «Нет чека» означает три разные вещи:
   услугу не оплатили вовсе (выручки нет), оплатили авансом и не пробили
   чек зачёта (выручка есть, нарушение в кассе), либо оплатили не деньгами —
   зачётом против гонорара врача (выручка есть, чек не нужен). Поэтому
   отсекать всё без чека нельзя: занизим выручку. */
function parseServices(wb){
  for (const name of wb.SheetNames){
    const rows = gridOf(wb.Sheets[name]);
    const H = findHead(rows, ["Дата работ", "Клиент", "Сумма", "Чек пробит"]);
    if (!H) continue;
    const ci = {};
    ["Дата работ","Номер","Клиент","Клиника","Врач","Вид операции","Ответственный",
     "Сумма","Касса","Чек пробит"].forEach(k => ci[k] = H.h.indexOf(k));
    const recs = [];
    for (let r = H.r + 1; r < rows.length; r++){
      const строка = rows[r];
      if (!S(строка[ci["Номер"]])) continue;
      if (S(строка[ci["Вид операции"]]) !== "Продажа клиенту") continue;
      recs.push({
        day: dayOf(строка[ci["Дата работ"]]),
        время: (S(строка[ci["Дата работ"]]).match(/\d{1,2}:\d{2}:\d{2}/) || [""])[0],
        num: S(строка[ci["Номер"]]), client: S(строка[ci["Клиент"]]),
        врач: S(строка[ci["Врач"]]), клиника: S(строка[ci["Клиника"]]),
        кто: S(строка[ci["Ответственный"]]),
        /* касса документа — единственный способ отнести наличные к аппарату:
           у строки реестра оплат самой кассы нет */
        касса: S(строка[ci["Касса"]]),
        sum: num(строка[ci["Сумма"]]),
        чек: /не пробиты/i.test(S(строка[ci["Чек пробит"]])) ? false : true
      });
    }
    if (recs.length) return {kind:"услуги", recs};
  }
  return null;
}

function безЧека(recs, поДням){
  const сЧеком = {}, без = [];
  let итогСЧеком = 0, итогБез = 0;
  for (const r of recs){
    if (r.чек){ сЧеком[r.day] = (сЧеком[r.day] || 0) + r.sum; итогСЧеком += r.sum; }
    else if (r.sum > 0){ без.push(r); итогБез += r.sum; }
  }
  /* сколько непробитого реально доехало до выручки: столько, на сколько
     реализация в выгрузке больше суммы услуг с чеком */
  let прошло = 0;
  const дни = [];
  const все = [...new Set(Object.keys(поДням).concat(Object.keys(сЧеком)))].sort();
  for (const day of все){
    const было = сЧеком[day] || 0;
    const стало = (поДням[day] || {}).tovary || (поДням[day] || {}).rev || 0;
    дни.push({day, было, стало, сверх: R2(стало - было)});
    if (стало > было) прошло += стало - было;
  }
  без.sort((a, b) => b.sum - a.sum);
  return {сЧеком: итогСЧеком, без: итогБез, список: без, прошло: R2(прошло), дни};
}
